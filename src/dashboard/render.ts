// Renders one self-contained HTML document from a `DashboardData` domain object -- inline CSS
// (light/dark via `prefers-color-scheme`), no chart library and no CDN (zero-dep policy: CSS
// bars instead of a canvas/SVG chart library), every wide table wrapped for horizontal
// scrolling instead of overflowing the page. Pure and deterministic: this function reads
// nothing but its `data` argument and never calls `Date.now()` itself -- the one place "now"
// matters (the freshness banner's viewer-clock comparison) is deferred to a small inline
// `<script>` that runs in the READER's browser at view time, not at generation time, so the
// generated bytes themselves stay byte-identical for a fixed `data` (see
// test/unit/dashboard-render.test.ts's determinism case).

import type {
  AttributionPanel,
  CalibrationPanel,
  CohortPanel,
  CostPanel,
  DashboardData,
  FreshnessPanel,
  PanelMeta,
} from "./types.js";

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function fmtNum(n: number | null): string {
  return n === null ? "欠測" : String(n);
}

function fmtUsd(n: number | null): string {
  return n === null ? "欠測" : `$${n.toFixed(4)}`;
}

function fmtPercent(n: number | null): string {
  return n === null ? "欠測" : `${(n * 100).toFixed(1)}%`;
}

function fmtRatio(n: number | null): string {
  return n === null ? "欠測" : n.toFixed(2);
}

/** Clamps a ratio (e.g. 0.0-1.0-and-beyond) to a 0-100 CSS bar width -- a ratio can legitimately
 * exceed 1.0 (e.g. actual tokens over-shooting a prediction), but the bar itself never renders
 * past 100% of its track; the raw number is always printed alongside the bar too. */
function barWidthPercent(ratio: number | null, capAt = 1): string {
  if (ratio === null) return "0%";
  const clamped = Math.max(0, Math.min(ratio / capAt, 1));
  return `${(clamped * 100).toFixed(1)}%`;
}

function renderMetaLine(m: PanelMeta): string {
  return `<p class="panel-meta">N=${m.n} / 欠測率=${fmtPercent(m.missingRate)} / quality=${escapeHtml(m.qualityStatus)}</p>`;
}

function renderEmptyNotice(): string {
  return `<p class="empty-notice">データなし</p>`;
}

function renderCostPanel(panel: CostPanel): string {
  const rows =
    panel.groups.length === 0
      ? renderEmptyNotice()
      : `<div class="table-wrap"><table>
      <thead><tr><th>repo</th><th>month</th><th>records</th><th>priced</th><th>unpriced</th><th>unknown</th><th>priced-missing-cost</th><th>total cost (priced only)</th></tr></thead>
      <tbody>
        ${panel.groups
          .map(
            (g) => `<tr>
          <td>${escapeHtml(g.repo)}</td>
          <td>${escapeHtml(g.month)}</td>
          <td>${g.recordCount}</td>
          <td>${g.pricedCount}</td>
          <td>${g.unpricedCount}</td>
          <td>${g.unknownCount}</td>
          <td>${g.pricedMissingCostCount}</td>
          <td>${fmtUsd(g.totalCostUsd)}</td>
        </tr>`,
          )
          .join("\n")}
      </tbody>
    </table></div>`;

  return `<section id="panel-cost">
    <h2>1. Cost</h2>
    ${renderMetaLine(panel.meta)}
    <p class="panel-note">unpriced/unknown な record は total cost に含めていない (「$0」に潰していない -- priced が 0 件の repo x month は total cost を「欠測」表示)。</p>
    ${rows}
  </section>`;
}

function renderCalibrationPanel(panel: CalibrationPanel): string {
  const summaryLine =
    panel.sampleStatus === "insufficient_data"
      ? `<p class="panel-note">sample 不足 (predicted N=${panel.predictedRows.length}) -- 区間・平均は insufficient_data として非表示。個々の行は下表参照。</p>`
      : `<p class="panel-note">平均 ratio (actual tokens / predicted p50): ${fmtRatio(panel.averageRatioToP50)}</p>`;

  const predictedTable =
    panel.predictedRows.length === 0
      ? renderEmptyNotice()
      : `<div class="table-wrap"><table>
      <thead><tr><th>generated_at</th><th>cohort</th><th>predicted p50</th><th>predicted p80</th><th>actual tokens</th><th>actual cost</th><th>ratio (actual/p50)</th></tr></thead>
      <tbody>
        ${panel.predictedRows
          .map(
            (r) => `<tr>
          <td>${escapeHtml(r.generatedAt)}</td>
          <td>${escapeHtml(r.cohortDigest)}</td>
          <td>${fmtNum(r.predictedP50)}</td>
          <td>${fmtNum(r.predictedP80)}</td>
          <td>${r.actualTokens}</td>
          <td>${fmtUsd(r.actualCostUsd)}</td>
          <td>
            <div class="bar-track"><div class="bar-fill" style="width:${barWidthPercent(r.ratioToP50, 2)}"></div></div>
            ${fmtRatio(r.ratioToP50)}
          </td>
        </tr>`,
          )
          .join("\n")}
      </tbody>
    </table></div>`;

  const abstainReasonRows = Object.entries(panel.abstainReasonCounts).sort(([a], [b]) =>
    a.localeCompare(b),
  );
  const abstainTable =
    abstainReasonRows.length === 0
      ? `<p class="empty-notice">abstain なし</p>`
      : `<div class="table-wrap"><table>
      <thead><tr><th>abstain reason</th><th>count</th></tr></thead>
      <tbody>
        ${abstainReasonRows
          .map(([reason, count]) => `<tr><td>${escapeHtml(reason)}</td><td>${count}</td></tr>`)
          .join("\n")}
      </tbody>
    </table></div>`;

  return `<section id="panel-calibration">
    <h2>2. Forecast calibration</h2>
    ${renderMetaLine(panel.meta)}
    <p class="panel-note">区間 (信頼区間等) は計算しない -- sample 不足時は insufficient_data と正直に表示する (M1 DoD)。</p>
    ${summaryLine}
    <h3>Predicted (n=${panel.predictedRows.length})</h3>
    ${predictedTable}
    <h3>Abstained (n=${panel.abstainedCount})</h3>
    ${abstainTable}
  </section>`;
}

function renderAttributionPanel(panel: AttributionPanel): string {
  const table =
    panel.timeSeries.length === 0
      ? renderEmptyNotice()
      : `<div class="table-wrap"><table>
      <thead><tr><th>generated_at</th><th>source repo</th><th>exactly attributed</th><th>unbound</th><th>mixed</th><th>orphan</th><th>exact token ratio</th></tr></thead>
      <tbody>
        ${panel.timeSeries
          .map(
            (p) => `<tr>
          <td>${escapeHtml(p.generatedAt)}</td>
          <td>${escapeHtml(p.sourceRepo)}</td>
          <td>${p.exactlyAttributed}</td>
          <td>${p.unbound}</td>
          <td>${p.mixed}</td>
          <td>${p.orphan}</td>
          <td>
            <div class="bar-track"><div class="bar-fill" style="width:${barWidthPercent(p.exactAttributedTokenRatio)}"></div></div>
            ${fmtPercent(p.exactAttributedTokenRatio)}
          </td>
        </tr>`,
          )
          .join("\n")}
      </tbody>
    </table></div>`;

  const eligibility =
    panel.latestResearchEligible === null ? "欠測" : panel.latestResearchEligible ? "yes" : "no";

  return `<section id="panel-attribution">
    <h2>3. Attribution</h2>
    ${renderMetaLine(panel.meta)}
    <p class="panel-note">research_eligible (直近): ${escapeHtml(eligibility)}</p>
    ${table}
  </section>`;
}

function hoursAgoLabel(iso: string | null): string {
  if (iso === null) return "欠測";
  return escapeHtml(iso);
}

function renderFreshnessPanel(panel: FreshnessPanel): string {
  return `<section id="panel-freshness">
    <h2>4. Freshness</h2>
    ${renderMetaLine(panel.meta)}
    <div
      id="freshness-banner"
      class="freshness-banner freshness-unknown"
      data-generated-at="${escapeHtml(panel.generatedAt)}"
      data-pipeline-heartbeat-at="${panel.pipelineHeartbeatAt ? escapeHtml(panel.pipelineHeartbeatAt) : ""}"
      data-last-valid-event-at="${panel.lastValidEventAt ? escapeHtml(panel.lastValidEventAt) : ""}"
    >
      <p class="freshness-text">(JavaScript 無効時はここに表示されません -- 下の生の値を参照してください)</p>
    </div>
    <ul class="freshness-raw">
      <li>pipeline_heartbeat_at (直近の workflow 実行): ${hoursAgoLabel(panel.pipelineHeartbeatAt)}</li>
      <li>last_valid_event_at (直近の有効データ): ${hoursAgoLabel(panel.lastValidEventAt)}</li>
      <li>このダッシュボードの生成時刻: ${escapeHtml(panel.generatedAt)}</li>
    </ul>
  </section>`;
}

function renderCohortPanel(panel: CohortPanel): string {
  const table =
    panel.groups.length === 0
      ? renderEmptyNotice()
      : `<div class="table-wrap"><table>
      <thead><tr><th>cohort_digest</th><th>records</th><th>total actual cost</th></tr></thead>
      <tbody>
        ${panel.groups
          .map(
            (g) => `<tr>
          <td>${escapeHtml(g.cohortDigest)}</td>
          <td>${g.recordCount}</td>
          <td>${fmtUsd(g.totalActualCostUsd)}</td>
        </tr>`,
          )
          .join("\n")}
      </tbody>
    </table></div>`;

  return `<section id="panel-cohort">
    <h2>5. Model cohort</h2>
    ${renderMetaLine(panel.meta)}
    <p class="panel-caveat">${escapeHtml(panel.caveat)}</p>
    ${table}
  </section>`;
}

