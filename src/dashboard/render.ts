/** One small, inline, no-dependency comparison of the VIEWER's current clock against the three
 * timestamps embedded on #freshness-banner's data-* attributes -- deliberately not computed at
 * generation time (spec: "生成時刻と閲覧時刻を JS 1行で比較"), and deliberately reporting the
 * heartbeat and last-valid-event axes as two independent findings so a reader can tell "the
 * runner stopped executing" apart from "the runner is fine, there's just nothing new." */
const FRESHNESS_SCRIPT = `
(function () {
  var el = document.getElementById("freshness-banner");
  if (!el) return;
  var nowMs = Date.now();
  function hoursSince(iso) {
    if (!iso) return null;
    var t = Date.parse(iso);
    return Number.isNaN(t) ? null : (nowMs - t) / 3600000;
  }
  var hb = hoursSince(el.getAttribute("data-pipeline-heartbeat-at"));
  var ev = hoursSince(el.getAttribute("data-last-valid-event-at"));
  var messages = [];
  var level = "ok";
  if (hb === null) { messages.push("pipeline heartbeat が記録されていません (pipeline が動いていない可能性)"); level = "red"; }
  else if (hb >= 48) { messages.push("pipeline heartbeat が48時間以上更新されていません (pipeline 停止の可能性)"); level = "red"; }
  else if (hb >= 24) { messages.push("pipeline heartbeat が24時間以上更新されていません"); level = "yellow"; }
  if (ev === null) { messages.push("有効なデータイベントが記録されていません"); if (level !== "red") level = "yellow"; }
  else if (ev >= 48) { messages.push("新しいタスクデータが48時間以上ありません (pipeline は動いているが新規データが無い可能性)"); if (level !== "red") level = "yellow"; }
  else if (ev >= 24) { messages.push("新しいタスクデータが24時間以上ありません"); if (level === "ok") level = "yellow"; }
  if (messages.length === 0) messages.push("直近24時間以内に pipeline heartbeat / データの両方を確認済みです");
  el.className = "freshness-banner freshness-" + level;
  var textEl = el.querySelector(".freshness-text");
  if (textEl) textEl.textContent = messages.join(" / ");
})();
`;

export function renderDashboardHtml(data: DashboardData): string {
  return `<!doctype html>
<html lang="ja">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>agent-metrics dashboard</title>
<style>${STYLE}</style>
</head>
<body>
<h1>agent-metrics dashboard</h1>
<p class="panel-meta">生成時刻: ${escapeHtml(data.generatedAt)}</p>
<p class="panel-note">因果を主張しない: このダッシュボードはコスト・件数・速度の記述的な観測のみを示す。品質は測定していない (quality_status: not_measured)。</p>
${renderCostPanel(data.cost)}
${renderCalibrationPanel(data.calibration)}
${renderAttributionPanel(data.attribution)}
${renderFreshnessPanel(data.freshness)}
${renderCohortPanel(data.cohort)}
<footer>agent-metrics-harvester dashboard generator</footer>
<script>${FRESHNESS_SCRIPT}</script>
</body>
</html>
`;
}
